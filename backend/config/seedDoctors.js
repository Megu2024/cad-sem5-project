export const seedDoctors = async () => {
  try {
    const count = await doctorModel.countDocuments();
    if (count === 0) {
      console.log('Seeding initial doctors into MongoDB Atlas...');
      const salt = await bcrypt.genSalt(10);
      const hashedPassword = await bcrypt.hash('12345678', salt);

      const docsToInsert = initialDoctors.map((doc) => ({
        ...doc,
        password: hashedPassword,
        date: Date.now(),
        slots_booked: {},
      }));

      await doctorModel.insertMany(docsToInsert);
      console.log('Successfully seeded 15 doctors into MongoDB Atlas!');
    }
  } catch (error) {
    console.log('Doctor seeding error:', error.message);
  }
};
